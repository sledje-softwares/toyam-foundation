// Review aid for the category → field maps (config/templates/maps/*.yaml, docs/09-template-model.md).
//
//   node scripts/check-maps.ts            report per template; exit 1 on errors or on anything not reviewed
//   node scripts/check-maps.ts --report   same report, exit 1 only on errors
//
// Per template it lists: categories the map does not list at all (add them, `{}` when a file of that kind is
// evidence for no field), fields no category maps to that are not in `unmapped_fields` (map them or list them),
// and validation errors (unknown category / field, score outside (0, 1]). Run it after changing a template's fields
// or _categories.yaml.
import { basename } from 'node:path';
import {
  TEMPLATES_DIR, type TemplateYaml, checkCategoryMap, readCategoryMap, readYaml, templateFiles,
} from '../src/template-config.ts';

const reportOnly = process.argv.includes('--report');
const categories = readYaml<Array<{ code: string }>>(`${TEMPLATES_DIR}_categories.yaml`);
const codes = categories.map((c) => c.code);

let errors = 0;
let open = 0;
for (const file of templateFiles()) {
  const t = readYaml<TemplateYaml>(file);
  const name = basename(file);
  let map;
  try {
    map = readCategoryMap(t, file);
  } catch (e) {
    console.log(`${name}: ✖ ${(e as Error).message}`);
    errors += 1;
    continue;
  }
  if (!map) {
    console.log(`${name}: no category_map (files labelled without the LLM get no field matches)`);
    open += 1;
    continue;
  }
  const r = checkCategoryMap(map, t, codes);
  const fields = t.sections.flatMap((s) => s.fields ?? []).length;
  const status = map.reviewed ? 'reviewed' : 'NOT reviewed';
  console.log(`${name} → ${t.category_map}: ${r.pairs} pairs, ${codes.length - r.missingCategories.length - r.emptyCategories.length}/${codes.length} categories mapped, `
    + `${fields - r.unreviewedFields.length - r.acceptedUnmappedFields.length}/${fields} fields mapped; ${status}`
    + (map.generated_by ? ` (generated by ${map.generated_by})` : ''));
  for (const e of r.errors) console.log(`  ✖ ${e}`);
  if (r.missingCategories.length) console.log(`  ? categories not in the map: ${r.missingCategories.join(', ')}`);
  if (r.unreviewedFields.length) console.log(`  ? fields no category maps to (not in unmapped_fields): ${r.unreviewedFields.join(', ')}`);
  if (r.emptyCategories.length) console.log(`  · categories with no field (reviewed {}): ${r.emptyCategories.join(', ')}`);
  if (r.acceptedUnmappedFields.length) console.log(`  · fields with no evidence category (unmapped_fields): ${r.acceptedUnmappedFields.join(', ')}`);
  errors += r.errors.length;
  open += r.missingCategories.length + r.unreviewedFields.length;
}
if (errors) {
  console.error(`${errors} error(s).`);
  process.exit(1);
}
if (open && !reportOnly) {
  console.error(`${open} item(s) to review.`);
  process.exit(1);
}
console.log(open ? `${open} item(s) to review.` : 'All maps complete.');
